# -*- coding: utf-8 -*-
"""澄清的规则白名单：有些说法**没有量化标准**，让模型自己判断会漏问。

背景：收紧提示词把误澄清从 30.6% 压到 0 之后，全量 60 题里该澄清的从 6/6 掉到 3/6 ——
模型开始"能兜就兜"，把「最近的销售情况」「客户增长情况」「大客户」这类全放过去了。
这些问题的共同点是：**桶里没有对应的量化定义，模型只能用默认值瞎猜**，而猜错就是答非所问。

所以给它们加一层确定性的规则：命中就直接反问，不再依赖模型判断。
好处是可解释、可测试、还省一次模型调用；坏处是规则要维护（所以只在"确实无法用默认值兜住"时才加）。

注意：规则只在**缺量化条件**时触发。比如「最近 30 天的成交额」有明确范围就不该问。
"""
from __future__ import annotations

import re

# ---- 相对时间：没有具体范围就问 ----
_RELATIVE_TIME = re.compile(r"最近|近期|这段时间|这几天|这阵子|最近一段时间")
_TIME_RANGE = re.compile(
    r"\d+\s*(天|日|周|个月|月|年|季度)"           # 最近 30 天 / 最近 3 个月
    r"|20\d{2}"                                    # 2024 年
    r"|本月|上月|本周|上周|今年|去年|本季度|上季度|第一季度|第二季度|第三季度|第四季度"
)

# ---- 没有量化标准的业务词 ----
_NO_STANDARD_TERMS = re.compile(r"大客户|重要客户|重点客户|头部客户|优质客户|异常|正常吗|有问题吗")
# ---- 指标不明的泛问 ----
_VAGUE_INTENT = re.compile(
    r"销售情况|情况怎么样|情况如何|表现如何|表现怎么样|增长情况|增长如何|趋势如何|趋势怎么样"
    r"|卖得好|看看数据|看一下数据|分析一下|给点建议|怎么样\?|怎么样？"
)
# 如果同时出现明确的指标词，就不算模糊
_CLEAR_METRIC = re.compile(r"成交额|销售额|订单数|订单量|数量|金额|个数|多少人|多少个|多少单|排名|占比|平均|最高|最低")


def clarify_rule(question: str) -> str | None:
    """命中规则就返回要反问用户的那句话；没命中返回 None（交给模型判断）。"""
    q = (question or "").strip()
    if not q:
        return None

    # 1) 相对时间但没有给出具体范围
    if _RELATIVE_TIME.search(q) and not _TIME_RANGE.search(q):
        return "你说的「最近」是指多长时间？比如最近 7 天、30 天，还是某个月份？"

    # 2) 没有量化标准的业务词（"活跃客户"在口径里有定义，不在这一类）
    if _NO_STANDARD_TERMS.search(q):
        return "这个说法在库里没有明确标准，你说的具体是指什么？比如按消费金额还是订单数来界定。"

    # 3) 指标不明的泛问（如果同时说了明确指标，就不算）
    if _VAGUE_INTENT.search(q) and not _CLEAR_METRIC.search(q):
        return "你想看哪个指标？比如成交额、订单数，还是退款金额；另外看哪段时间？"

    return None
